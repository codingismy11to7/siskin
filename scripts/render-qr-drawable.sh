#!/usr/bin/env bash
# Renders a URL as a QR code vector drawable, one module per viewport unit.
#
#   scripts/render-qr-drawable.sh https://siskinapp.com/credits \
#     app/src/main/res/drawable/qr_credits.xml
#
# The drawable paints its own white background and four-module quiet zone,
# because a scanner needs dark-on-light and the dialog behind it may be dark.
# QrDrawableTest decodes the result, so a stale drawable fails the build.
set -euo pipefail

url=$1
out=$2

nix run nixpkgs#qrencode -- -t ASCII -m 0 -l M "$url" |
  awk -v url="$url" '
    # qrencode draws each module two characters wide.
    {
      row = NR - 1
      n = length($0) / 2
      x = 0
      while (x < n) {
        if (substr($0, 2 * x + 1, 1) == "#") {
          start = x
          while (x < n && substr($0, 2 * x + 1, 1) == "#") x++
          path = path sprintf("M%d,%dh%dv1h-%dz", start + 4, row + 4, x - start, x - start)
        } else {
          x++
        }
      }
      size = n
    }
    END {
      side = size + 8
      print "<?xml version=\"1.0\" encoding=\"utf-8\"?>"
      print "<!-- " url ", generated by scripts/render-qr-drawable.sh. Do not edit. -->"
      print "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\""
      printf "    android:width=\"%ddp\"\n", side * 4
      printf "    android:height=\"%ddp\"\n", side * 4
      printf "    android:viewportWidth=\"%d\"\n", side
      printf "    android:viewportHeight=\"%d\">\n", side
      printf "    <path\n        android:fillColor=\"#FFFFFFFF\"\n        android:pathData=\"M0,0h%dv%dh-%dz\" />\n", side, side, side
      printf "    <path\n        android:fillColor=\"#FF000000\"\n        android:pathData=\"%s\" />\n", path
      print "</vector>"
    }
  ' >"$out"
